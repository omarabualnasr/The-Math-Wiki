export interface MathSymbol {
  id: string;
  symbol: string;
  name: string;
  category: SymbolCategory;
  latex: string;
  description: string;
  unicode: string;
  aliases?: string[];
}

const make = (symbol: string, name: string, category: SymbolCategory, latex: string, description: string, aliases: string[] = []): MathSymbol => ({
  id: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, ''),
  symbol, name, category, latex, description,
  unicode: [...symbol].map((character) => `U+${character.codePointAt(0)!.toString(16).toUpperCase().padStart(4, '0')}`).join(' '),
  aliases,
});

